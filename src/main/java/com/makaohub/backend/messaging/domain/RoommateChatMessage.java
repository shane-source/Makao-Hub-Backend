package com.makaohub.backend.messaging.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.CreationTimestamp;

import java.time.Instant;
import java.util.Objects;
import java.util.UUID;
import java.util.regex.Pattern;

@Entity
@Table(name = "roommate_chat_messages")
public class RoommateChatMessage {

    public static final int MAX_BODY_LENGTH = 2_000;
    public static final int MAX_MODERATION_REASON_LENGTH = 50;

    /*
     * Moderation reasons are safe internal codes, not free-form text.
     *
     * Valid examples:
     * CONTACT_DETAILS
     * PHONE_NUMBER
     * SOCIAL_HANDLE
     *
     * This prevents accidentally storing detected phone numbers,
     * email addresses or other personal data in the reason column.
     */
    private static final Pattern MODERATION_REASON_PATTERN =
            Pattern.compile("[A-Z][A-Z0-9_]{0,49}");

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /*
     * The thread relationship is represented by its UUID instead of
     * a JPA object relationship.
     *
     * This avoids accidentally loading or serializing an entire chat
     * thread when only the identifier is required.
     */
    @Column(
            name = "chat_thread_id",
            nullable = false,
            updatable = false
    )
    private UUID chatThreadId;

    /*
     * senderId is always determined from the verified JWT.
     * It must never be accepted as authoritative client input.
     */
    @Column(
            name = "sender_id",
            nullable = false,
            updatable = false
    )
    private UUID senderId;

    /*
     * Generated by the client for one logical send operation.
     *
     * If a WebSocket frame is retried, it must reuse this UUID.
     * The database unique constraint then prevents duplicate messages.
     */
    @Column(
            name = "client_message_id",
            nullable = false,
            updatable = false
    )
    private UUID clientMessageId;

    /*
     * Only sanitized text is stored.
     *
     * There is deliberately no originalBody field because original
     * phone numbers or social handles must not be recoverable later.
     */
    @Column(
            name = "masked_body",
            nullable = false,
            updatable = false,
            columnDefinition = "TEXT"
    )
    private String maskedBody;

    @Enumerated(EnumType.STRING)
    @Column(
            name = "moderation_status",
            nullable = false,
            updatable = false,
            length = 20
    )
    private MessageModerationStatus moderationStatus;

    /*
     * A safe machine-readable code explaining why the message was
     * flagged. It never contains the detected contact information.
     */
    @Column(
            name = "moderation_reason",
            updatable = false,
            length = MAX_MODERATION_REASON_LENGTH
    )
    private String moderationReason;

    /*
     * Messages are append-only. There is intentionally no updatedAt
     * field and no message-editing method.
     */
    @CreationTimestamp
    @Column(
            name = "created_at",
            nullable = false,
            updatable = false
    )
    private Instant createdAt;

    /**
     * Required by JPA.
     *
     * Application code should use clean(...) or flagged(...) instead.
     */
    protected RoommateChatMessage() {
    }

    private RoommateChatMessage(
            UUID chatThreadId,
            UUID senderId,
            UUID clientMessageId,
            String maskedBody,
            MessageModerationStatus moderationStatus,
            String moderationReason
    ) {
        this.chatThreadId = Objects.requireNonNull(
                chatThreadId,
                "Chat thread ID is required."
        );

        this.senderId = Objects.requireNonNull(
                senderId,
                "Sender ID is required."
        );

        this.clientMessageId = Objects.requireNonNull(
                clientMessageId,
                "Client message ID is required."
        );

        this.maskedBody = normalizeBody(maskedBody);

        this.moderationStatus = Objects.requireNonNull(
                moderationStatus,
                "Moderation status is required."
        );

        this.moderationReason = validateModerationReason(
                moderationStatus,
                moderationReason
        );
    }

    /**
     * Creates a message that contains no detected contact-sharing
     * pattern.
     */
    public static RoommateChatMessage clean(
            UUID chatThreadId,
            UUID senderId,
            UUID clientMessageId,
            String maskedBody
    ) {
        return new RoommateChatMessage(
                chatThreadId,
                senderId,
                clientMessageId,
                maskedBody,
                MessageModerationStatus.CLEAN,
                null
        );
    }

    /**
     * Creates a sanitized message whose original input contained a
     * prohibited pattern.
     *
     * maskedBody must already contain the masked version. The original
     * text is never passed into a persistence field.
     */
    public static RoommateChatMessage flagged(
            UUID chatThreadId,
            UUID senderId,
            UUID clientMessageId,
            String maskedBody,
            String moderationReason
    ) {
        return new RoommateChatMessage(
                chatThreadId,
                senderId,
                clientMessageId,
                maskedBody,
                MessageModerationStatus.FLAGGED,
                moderationReason
        );
    }

    /**
     * Normalizes and validates the already-masked message.
     *
     * Complexity is O(m), where m is the message length and m cannot
     * exceed 2,000 characters.
     */
    private static String normalizeBody(
            String maskedBody
    ) {
        if (maskedBody == null) {
            throw new IllegalArgumentException(
                    "Message body is required."
            );
        }

        String normalizedBody = maskedBody.strip();

        if (normalizedBody.isEmpty()) {
            throw new IllegalArgumentException(
                    "Message body cannot be empty."
            );
        }

        if (normalizedBody.length() > MAX_BODY_LENGTH) {
            throw new IllegalArgumentException(
                    "Message body cannot exceed "
                            + MAX_BODY_LENGTH
                            + " characters."
            );
        }

        return normalizedBody;
    }

    /**
     * Enforces consistency between moderation status and reason.
     *
     * A CLEAN message cannot have a reason.
     * A FLAGGED message must have a safe uppercase reason code.
     */
    private static String validateModerationReason(
            MessageModerationStatus moderationStatus,
            String moderationReason
    ) {
        if (moderationStatus == MessageModerationStatus.CLEAN) {
            if (moderationReason != null) {
                throw new IllegalArgumentException(
                        "A clean message cannot have a moderation reason."
                );
            }

            return null;
        }

        if (moderationReason == null) {
            throw new IllegalArgumentException(
                    "A flagged message requires a moderation reason."
            );
        }

        String normalizedReason = moderationReason
                .strip()
                .toUpperCase();

        if (!MODERATION_REASON_PATTERN
                .matcher(normalizedReason)
                .matches()) {
            throw new IllegalArgumentException(
                    "Moderation reason must be a safe uppercase code."
            );
        }

        return normalizedReason;
    }

    public UUID getId() {
        return id;
    }

    public UUID getChatThreadId() {
        return chatThreadId;
    }

    public UUID getSenderId() {
        return senderId;
    }

    public UUID getClientMessageId() {
        return clientMessageId;
    }

    public String getMaskedBody() {
        return maskedBody;
    }

    public MessageModerationStatus getModerationStatus() {
        return moderationStatus;
    }

    public String getModerationReason() {
        return moderationReason;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public boolean isFlagged() {
        return moderationStatus
                == MessageModerationStatus.FLAGGED;
    }
}